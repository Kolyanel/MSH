#ifndef IO_H
#define IO_H

#include <stdio.h>
#include <stddef.h>
#include <stdarg.h>
#include <unistd.h>

/* ============================================================
 * ФЛАГИ
 * ============================================================ */

#define RL_SHELL (1 << 0)   /* read_line: shell-режим (пустая строка возвращается как "") */

/* ============================================================
 * IO API
 * ============================================================ */

/*
 * Читает строку произвольной длины из потока fp.
 * Автоматически расширяет буфер, если строка не уместилась.
 *
 * flg — битовая маска:
 *   RL_SHELL — пустая строка допустима и возвращается как "".
 *              Без флага пустая строка означает EOF.
 *
 * Убирает завершающий '\n' и '\r'.
 * Возвращает строку (выделена через malloc) или NULL при EOF/ошибке.
 */
char *read_line(FILE *fp, int flg);

/*
 * Пишет len байт из buf в файловый дескриптор out_fd.
 * Если len == 0, длина определяется через strlen(buf).
 * В отличие от write(), гарантирует запись всех байт
 * (автоматически обрабатывает частичную запись и EINTR).
 *
 * Возвращает 0 при успехе, -1 при ошибке.
 */
int puts_fd(int out_fd, const char *buf, size_t len);

/*
 * Форматный вывод в файловый дескриптор out_fd.
 * Формирует строку через vsnprintf, затем пишет через puts_fd.
 *
 * Возвращает 0 при успехе, -1 при ошибке.
 */
int printf_fd(int out_fd, const char *fmt, ...);

/*
 * Читает всё содержимое файлового дескриптора in_fd до EOF.
 * *sizep — размер прочитанных данных в байтах (если не NULL).
 *
 * Возвращает строку (выделена через malloc) или NULL при ошибке.
 */
char *read_fd(int in_fd, size_t *sizep);

#endif // IO_H