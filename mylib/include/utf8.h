#ifndef UTF8_H
#define UTF8_H

#include <stddef.h>
#include <stdint.h>

/*
** ============================================================
** Один символ UTF-8
** ============================================================
**
** codepoint — кодовая точка Unicode.
** bytes     — количество байт UTF-8.
** width     — экранная ширина символа.
**
** Примеры:
**
**   'A'  -> U+0041 -> 1 байт -> 1 позиция
**   'я'  -> U+044F -> 2 байта -> 1 позиция
**   '界' -> U+754C -> 3 байта -> 2 позиции
**
** width — это именно количество экранных позиций терминала.
** Оно не равно количеству байт UTF-8.
** ============================================================
*/

typedef struct s_utf8_char
{
	uint32_t	codepoint;
	size_t		bytes;
	size_t		width;

}	t_utf8_char;

/*
** ============================================================
** Декодировать один UTF-8 символ
** ============================================================
**
** s     — начало последовательности.
** size  — количество реально доступных байт.
** out   — результат декодирования.
**
** Возвращает:
**
**    0 — успешно;
**   -1 — ошибка аргументов или некорректная UTF-8
**        последовательность.
**
** При ошибке вызывающий код может обработать первый байт
** как отдельный байт.
**
** Важно:
**
** Функция никогда не читает больше size байт.
** ============================================================
*/

int	utf8_decode(
		const char *s,
		size_t size,
		t_utf8_char *out);

/*
** ============================================================
** Длина текущего символа
** ============================================================
**
** Функция предназначена для NUL-terminated строки.
**
** Возвращает:
**
**   0 — если s == NULL;
**   1 — ASCII или некорректный первый байт;
**   2..4 — длина корректной UTF-8 последовательности.
** ============================================================
*/

size_t	utf8_char_len(
		const char *s);

/*
** ============================================================
** Экранная ширина текущего символа
** ============================================================
**
** Функция предназначена для NUL-terminated строки.
**
** Возвращает:
**
**   0 — управляющий или combining символ;
**   1 — обычный символ;
**   2 — широкий символ.
** ============================================================
*/

size_t	utf8_char_width(
		const char *s);

/*
** ============================================================
** Экранная ширина строки
** ============================================================
**
** ANSI escape-последовательности не занимают экранных
** позиций и поэтому не учитываются.
**
** Строка должна завершаться '\0'.
** ============================================================
*/

size_t	utf8_width(
		const char *s);

/*
** ============================================================
** Экранная ширина первых bytes байт строки
** ============================================================
**
** ANSI escape-последовательности не учитываются.
**
** Если bytes заканчивается внутри UTF-8 символа, неполный
** символ не учитывается.
** ============================================================
*/

size_t	utf8_width_n(
		const char *s,
		size_t bytes);

/*
** ============================================================
** Количество UTF-8 символов в строке
** ============================================================
**
** ANSI escape-последовательности не считаются символами.
**
** Это количество Unicode-кодовых точек, а не экранная ширина.
** ============================================================
*/

size_t	utf8_strlen(
		const char *s);

/*
** ============================================================
** Перейти к следующему UTF-8 символу
** ============================================================
**
** s должен указывать на начало UTF-8 символа.
**
** Для некорректного UTF-8 последовательность считается
** состоящей из одного байта.
** ============================================================
*/

const char	*utf8_next(
		const char *s);

/*
** ============================================================
** Перейти к предыдущему UTF-8 символу
** ============================================================
**
** start — начало строки.
** s     — текущая позиция.
**
** Если s == start, возвращается start.
** ============================================================
*/

const char	*utf8_prev(
		const char *start,
		const char *s);

/*
** ============================================================
** Получить количество байт для первых chars символов
** ============================================================
**
** ANSI escape-последовательности не считаются символами.
** ============================================================
*/

size_t	utf8_bytes_for_chars(
		const char *s,
		size_t chars);

/*
** ============================================================
** Выравнять позицию на границу UTF-8 символа
** ============================================================
**
** Если pos указывает на continuation byte, позиция
** перемещается назад до первого байта соответствующего
** UTF-8 символа.
**
** Функция предназначена для NUL-terminated строки или
** буфера, в котором pos уже находится в допустимых пределах.
** ============================================================
*/

size_t	utf8_align_boundary(
		const char *s,
		size_t pos);

/*
** ============================================================
** Получить длину ANSI escape-последовательности
** ============================================================
**
** Поддерживается CSI:
**
**     ESC [
**
** Например:
**
**     ESC[31m
**     ESC[0m
**     ESC[2K
**     ESC[6n
**
** Возвращается количество байт всей последовательности.
**
** Если s не начинается с ESC, возвращается 0.
**
** Если последовательность незавершена, возвращается длина
** уже имеющейся последовательности.
** ============================================================
*/

size_t	utf8_ansi_len(
		const char *s);

#endif